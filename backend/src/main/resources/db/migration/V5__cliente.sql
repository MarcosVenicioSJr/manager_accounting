-- Clientes do contador, sempre isolados por tenant_id, e o token que o cliente usa no app mobile.

CREATE TABLE cliente (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT        NOT NULL REFERENCES tenant (id),
    tipo_pessoa       VARCHAR(8)    NOT NULL,
    -- Só letras maiúsculas e números, sem pontuação: CPF com 11 dígitos, CNPJ com 14 (aceita o alfanumérico)
    documento         VARCHAR(14)   NOT NULL,
    -- Nome (pessoa física) ou razão social (pessoa jurídica)
    nome              VARCHAR(150)  NOT NULL,
    nome_fantasia     VARCHAR(150),
    email             VARCHAR(150),
    -- Só dígitos, com DDD
    telefone          VARCHAR(11),
    regime_tributario VARCHAR(20),
    observacoes       VARCHAR(1000),
    ativo             BOOLEAN       NOT NULL DEFAULT TRUE,
    data_inclusao     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    data_atualizacao  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- Controle de edição simultânea (optimistic lock do JPA)
    versao            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_cliente_tipo_pessoa CHECK (tipo_pessoa IN ('FISICA', 'JURIDICA')),
    CONSTRAINT ck_cliente_documento CHECK (
        (tipo_pessoa = 'FISICA' AND documento ~ '^[0-9]{11}$')
        OR (tipo_pessoa = 'JURIDICA' AND documento ~ '^[0-9A-Z]{12}[0-9]{2}$')
    ),
    CONSTRAINT ck_cliente_telefone CHECK (telefone ~ '^[0-9]{10,11}$'),
    CONSTRAINT ck_cliente_regime CHECK (
        regime_tributario IN ('MEI', 'SIMPLES_NACIONAL', 'LUCRO_PRESUMIDO', 'LUCRO_REAL')
    ),
    -- Regime tributário só faz sentido para pessoa jurídica
    CONSTRAINT ck_cliente_regime_pj CHECK (regime_tributario IS NULL OR tipo_pessoa = 'JURIDICA'),
    -- O mesmo CPF/CNPJ pode existir em escritórios diferentes, mas não duas vezes no mesmo
    CONSTRAINT uk_cliente_tenant_documento UNIQUE (tenant_id, documento)
);

CREATE INDEX ix_cliente_tenant_nome ON cliente (tenant_id, lower(nome));

-- Token de acesso do cliente ao app. Só o hash SHA-256 é guardado; o valor aparece uma única vez para o contador.
-- Cada cliente tem no máximo um token ativo (revogado_em nulo).
CREATE TABLE cliente_token_acesso (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id    BIGINT      NOT NULL REFERENCES cliente (id),
    token_hash    VARCHAR(64) NOT NULL,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now(),
    criado_por    BIGINT      NOT NULL REFERENCES usuario (id),
    revogado_em   TIMESTAMPTZ,
    -- Preenchido pelo app do cliente (próxima etapa)
    ultimo_uso_em TIMESTAMPTZ,
    CONSTRAINT uk_cliente_token_acesso_hash UNIQUE (token_hash)
);

CREATE UNIQUE INDEX uk_cliente_token_acesso_ativo ON cliente_token_acesso (cliente_id) WHERE revogado_em IS NULL;
