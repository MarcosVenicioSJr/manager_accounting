-- Usuários do escritório: perfil de acesso e convite por e-mail.

-- ADMIN gerencia os usuários do escritório e pode desativar/reativar clientes e revogar o acesso ao app.
-- USUARIO cadastra e edita clientes e gera o token do app.
ALTER TABLE usuario ADD COLUMN perfil VARCHAR(10) NOT NULL DEFAULT 'USUARIO';
ALTER TABLE usuario ADD CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMIN', 'USUARIO'));

-- Até aqui cada escritório tinha só o contador cadastrado pelo banco: ele vira o administrador.
UPDATE usuario SET perfil = 'ADMIN';

CREATE INDEX ix_usuario_tenant_perfil ON usuario (tenant_id, perfil) WHERE ativo;

-- Convite: o administrador informa nome, e-mail, login e perfil; a pessoa recebe um link para criar a senha.
-- O usuário já existe (login reservado) com uma senha aleatória que ninguém conhece; o primeiro acesso é feito
-- pelo link. Só o hash SHA-256 do token fica aqui.
CREATE TABLE convite_usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT      NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    token_hash    VARCHAR(64) NOT NULL,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now(),
    criado_por    BIGINT      NOT NULL REFERENCES usuario (id),
    expira_em     TIMESTAMPTZ NOT NULL,
    aceito_em     TIMESTAMPTZ,
    invalidado_em TIMESTAMPTZ,
    CONSTRAINT uk_convite_usuario_token_hash UNIQUE (token_hash)
);

CREATE INDEX ix_convite_usuario_usuario ON convite_usuario (usuario_id, criado_em);
CREATE INDEX ix_convite_usuario_expira_em ON convite_usuario (expira_em);
