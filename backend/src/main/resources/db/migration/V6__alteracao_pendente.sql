-- Alterações do "Meu perfil" que só valem depois de confirmadas por e-mail (troca de senha e troca de e-mail).
-- O token vai só no link do e-mail; aqui fica o hash SHA-256 dele.
--   tipo SENHA: valor_novo guarda o hash BCrypt da nova senha; referencia guarda o SHA-256 do hash da senha
--               atual no momento do pedido (se a senha mudar por outro caminho antes da confirmação, o pedido
--               deixa de valer).
--   tipo EMAIL: valor_novo guarda o novo e-mail (o link vai para ele); referencia guarda o e-mail atual.

CREATE TABLE alteracao_pendente (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT       NOT NULL REFERENCES usuario (id),
    tipo          VARCHAR(10)  NOT NULL,
    valor_novo    VARCHAR(150) NOT NULL,
    referencia    VARCHAR(150),
    token_hash    VARCHAR(64)  NOT NULL,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expira_em     TIMESTAMPTZ  NOT NULL,
    confirmado_em TIMESTAMPTZ,
    invalidado_em TIMESTAMPTZ,
    CONSTRAINT ck_alteracao_pendente_tipo CHECK (tipo IN ('SENHA', 'EMAIL')),
    CONSTRAINT uk_alteracao_pendente_token_hash UNIQUE (token_hash)
);

CREATE INDEX ix_alteracao_pendente_usuario ON alteracao_pendente (usuario_id, tipo, criado_em);
CREATE INDEX ix_alteracao_pendente_expira_em ON alteracao_pendente (expira_em);
