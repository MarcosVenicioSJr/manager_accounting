-- Tenants (escritórios de contabilidade) e o tema (cores e logo) carregado após o login.

CREATE TABLE tenant (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_empresa  VARCHAR(150) NOT NULL,
    guid          UUID         NOT NULL DEFAULT gen_random_uuid(),
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    data_inclusao TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_tenant_guid UNIQUE (guid)
);

-- A logo é um arquivo dentro do projeto web: web/public/tenants/<guid>/<logo_arquivo>
CREATE TABLE tenant_tema (
    tenant_id      BIGINT PRIMARY KEY REFERENCES tenant (id),
    cor_primaria   VARCHAR(7),
    cor_secundaria VARCHAR(7),
    logo_arquivo   VARCHAR(100),
    CONSTRAINT ck_tenant_tema_cor_primaria CHECK (cor_primaria ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_tenant_tema_cor_secundaria CHECK (cor_secundaria ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_tenant_tema_logo_arquivo CHECK (logo_arquivo ~ '^[A-Za-z0-9_-][A-Za-z0-9._-]*$')
);
