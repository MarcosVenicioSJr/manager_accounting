-- Tokens de redefinição de senha ("Esqueceu sua senha?").
-- Só o hash SHA-256 do token é guardado; o valor original vai apenas no link do e-mail.
-- O token é de uso único: utilizado_em marca o uso; invalidado_em marca tokens anulados por um pedido
-- mais novo ou por uma redefinição concluída.

CREATE TABLE token_redefinicao_senha (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT      NOT NULL REFERENCES usuario (id),
    token_hash    VARCHAR(64) NOT NULL,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now(),
    expira_em     TIMESTAMPTZ NOT NULL,
    utilizado_em  TIMESTAMPTZ,
    invalidado_em TIMESTAMPTZ,
    CONSTRAINT uk_token_redefinicao_senha_hash UNIQUE (token_hash)
);

CREATE INDEX ix_token_redefinicao_senha_usuario ON token_redefinicao_senha (usuario_id, criado_em);
CREATE INDEX ix_token_redefinicao_senha_expira_em ON token_redefinicao_senha (expira_em);
