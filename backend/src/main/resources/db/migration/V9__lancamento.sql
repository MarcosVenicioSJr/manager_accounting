-- Lançamentos do cliente: compras, dívidas e despesas, com categoria fixa (lista do sistema) e comprovante opcional.
-- O escritório lança pelo backoffice e, mais tarde, o cliente lança pelo app (coluna origem).
-- Nada é apagado de verdade: a exclusão é lógica (excluido_em) e cada mudança fica em lancamento_historico.

-- Garante no banco que o cliente do lançamento é do mesmo escritório (além da regra no backend)
ALTER TABLE cliente ADD CONSTRAINT uk_cliente_id_tenant UNIQUE (id, tenant_id);

CREATE TABLE lancamento (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id              BIGINT         NOT NULL REFERENCES tenant (id),
    cliente_id             BIGINT         NOT NULL,
    tipo                   VARCHAR(10)    NOT NULL,
    -- Dia da compra, da dívida ou da despesa (sem hora)
    data                   DATE           NOT NULL,
    descricao              VARCHAR(200)   NOT NULL,
    -- Descrição em minúsculas e sem acentos, para a busca ("cafe" encontra "Café"). O backend preenche.
    busca                  VARCHAR(200)   NOT NULL,
    valor                  NUMERIC(14, 2) NOT NULL,
    categoria              VARCHAR(40)    NOT NULL,
    -- Quem criou: ESCRITORIO (backoffice) ou CLIENTE (app)
    origem                 VARCHAR(10)    NOT NULL,
    -- Comprovante (opcional). O arquivo fica fora do banco; aqui só a chave dele no armazenamento.
    comprovante_chave      VARCHAR(200),
    comprovante_nome       VARCHAR(200),
    comprovante_tipo       VARCHAR(50),
    comprovante_tamanho    BIGINT,
    criado_em              TIMESTAMPTZ    NOT NULL DEFAULT now(),
    -- Usuário do escritório; nulo quando foi o cliente pelo app
    criado_por_usuario_id  BIGINT REFERENCES usuario (id),
    atualizado_em          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    atualizado_por_usuario_id BIGINT REFERENCES usuario (id),
    -- Preenchido quando o lançamento foi alterado depois de criado (mostra o selo "Editado")
    editado_em             TIMESTAMPTZ,
    excluido_em            TIMESTAMPTZ,
    excluido_por_usuario_id BIGINT REFERENCES usuario (id),
    -- Controle de edição simultânea (optimistic lock do JPA)
    versao                 BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT fk_lancamento_cliente_tenant FOREIGN KEY (cliente_id, tenant_id) REFERENCES cliente (id, tenant_id),
    CONSTRAINT ck_lancamento_tipo CHECK (tipo IN ('COMPRA', 'DIVIDA', 'DESPESA')),
    CONSTRAINT ck_lancamento_origem CHECK (origem IN ('ESCRITORIO', 'CLIENTE')),
    CONSTRAINT ck_lancamento_valor CHECK (valor > 0),
    CONSTRAINT ck_lancamento_descricao CHECK (length(btrim(descricao)) > 0),
    CONSTRAINT ck_lancamento_categoria CHECK (categoria IN (
        'ALIMENTACAO', 'ALUGUEL', 'ENERGIA_AGUA', 'INTERNET_TELEFONE', 'COMBUSTIVEL_TRANSPORTE',
        'MERCADORIAS_FORNECEDORES', 'MATERIAL_ESCRITORIO', 'EQUIPAMENTOS', 'MANUTENCAO', 'SERVICOS_TERCEIROS',
        'FOLHA_PRO_LABORE', 'IMPOSTOS_TAXAS', 'TARIFAS_BANCARIAS', 'EMPRESTIMOS_FINANCIAMENTOS', 'CARTAO_CREDITO',
        'MARKETING', 'SAUDE', 'EDUCACAO', 'OUTROS')),
    -- Comprovante: os quatro campos juntos, ou nenhum
    CONSTRAINT ck_lancamento_comprovante CHECK (
        (comprovante_chave IS NULL AND comprovante_nome IS NULL AND comprovante_tipo IS NULL
            AND comprovante_tamanho IS NULL)
        OR (comprovante_chave IS NOT NULL AND comprovante_nome IS NOT NULL AND comprovante_tipo IS NOT NULL
            AND comprovante_tamanho > 0)),
    CONSTRAINT ck_lancamento_exclusao CHECK (excluido_em IS NOT NULL OR excluido_por_usuario_id IS NULL)
);

-- Listas: sempre por tenant, só os não excluídos, do mais recente para o mais antigo
CREATE INDEX ix_lancamento_tenant_data ON lancamento (tenant_id, data DESC, id DESC) WHERE excluido_em IS NULL;
CREATE INDEX ix_lancamento_cliente_data ON lancamento (cliente_id, data DESC, id DESC) WHERE excluido_em IS NULL;

-- Histórico: uma linha por ação, com o estado do lançamento logo depois dela (em JSON).
-- Comparando uma linha com a anterior dá para ver o que mudou e quem mudou.
CREATE TABLE lancamento_historico (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lancamento_id     BIGINT      NOT NULL REFERENCES lancamento (id),
    tenant_id         BIGINT      NOT NULL REFERENCES tenant (id),
    acao              VARCHAR(10) NOT NULL,
    origem            VARCHAR(10) NOT NULL,
    usuario_id        BIGINT REFERENCES usuario (id),
    feito_em          TIMESTAMPTZ NOT NULL DEFAULT now(),
    dados             JSONB       NOT NULL,
    CONSTRAINT ck_lancamento_historico_acao CHECK (acao IN ('CRIAR', 'EDITAR', 'EXCLUIR')),
    CONSTRAINT ck_lancamento_historico_origem CHECK (origem IN ('ESCRITORIO', 'CLIENTE'))
);

CREATE INDEX ix_lancamento_historico_lancamento ON lancamento_historico (lancamento_id, feito_em, id);
