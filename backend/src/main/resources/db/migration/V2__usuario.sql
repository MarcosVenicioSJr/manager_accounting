-- Usuários (contadores). Login único na plataforma inteira (sem diferenciar maiúsculas de minúsculas).
-- Cadastro direto no banco, com a senha temporária já em hash BCrypt em senha_hash (ver docs/sql/seed-dev.sql).
-- O primeiro acesso troca o hash e preenche nome, e-mail e telefone.

CREATE TABLE usuario (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id                 BIGINT       NOT NULL REFERENCES tenant (id),
    login                     VARCHAR(60)  NOT NULL,
    senha_hash                VARCHAR(100) NOT NULL,
    nome_completo             VARCHAR(150),
    email                     VARCHAR(150),
    telefone                  VARCHAR(20),
    ativo                     BOOLEAN      NOT NULL DEFAULT TRUE,
    primeiro_acesso_concluido BOOLEAN      NOT NULL DEFAULT FALSE,
    tentativas_falhas         INTEGER      NOT NULL DEFAULT 0,
    bloqueado_ate             TIMESTAMPTZ,
    data_inclusao             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuario_primeiro_acesso CHECK (
        NOT primeiro_acesso_concluido
        OR (nome_completo IS NOT NULL AND email IS NOT NULL AND telefone IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uk_usuario_login ON usuario (lower(login));
CREATE INDEX ix_usuario_tenant ON usuario (tenant_id);
